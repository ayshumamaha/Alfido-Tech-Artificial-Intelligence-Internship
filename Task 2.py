# Rock Paper Scissors Image Classification

import os
import random
import numpy as np
import matplotlib.pyplot as plt
import tensorflow as tf

from tensorflow.keras import layers, models

print("=" * 60)
print("ROCK PAPER SCISSORS IMAGE CLASSIFICATION")
print("=" * 60)

np.random.seed(42)
random.seed(42)
tf.random.set_seed(42)

IMG_SIZE = 64
SAMPLES = 300

# Generate synthetic gesture-like images
# These are simple shape illustrations, not real hand photos.

def create_image(label):
    img = np.zeros((IMG_SIZE, IMG_SIZE, 1), dtype=np.float32)

    if label == 0:  # Rock
        x1, y1 = np.random.randint(15, 25), np.random.randint(15, 25)
        x2, y2 = np.random.randint(40, 50), np.random.randint(40, 50)
        img[y1:y2, x1:x2, 0] = 1

    elif label == 1:  # Paper
        x1, y1 = np.random.randint(10, 20), np.random.randint(10, 20)
        x2, y2 = np.random.randint(45, 55), np.random.randint(45, 55)
        img[y1:y2, x1:x2, 0] = 1

    else:  # Scissors
        for i in range(10, 54):
            img[i, i, 0] = 1
            img[i, 63-i, 0] = 1
            if i + 1 < 64:
                img[i, i+1, 0] = 1
                img[i, 63-i, 0] = 1

    # Random shifting to create variations
    shift_x = np.random.randint(-5, 6)
    shift_y = np.random.randint(-5, 6)

    img = np.roll(img, shift_x, axis=1)
    img = np.roll(img, shift_y, axis=0)

    # Add noise
    img += np.random.normal(0, 0.05, img.shape)
    img = np.clip(img, 0, 1)

    return img

# Generate dataset
X, y = [], []

for label in range(3):
    for _ in range(SAMPLES):
        X.append(create_image(label))
        y.append(label)

X = np.array(X)
y = np.array(y)

# Shuffle
indices = np.random.permutation(len(X))
X, y = X[indices], y[indices]

# Train-test split
split = int(0.8 * len(X))
X_train, X_test = X[:split], X[split:]
y_train, y_test = y[:split], y[split:]

print("Training samples:", len(X_train))
print("Testing samples:", len(X_test))

# CNN Model
model = models.Sequential([
    layers.Input(shape=(IMG_SIZE, IMG_SIZE, 1)),
    layers.Conv2D(16, 3, activation="relu"),
    layers.MaxPooling2D(),
    layers.Conv2D(32, 3, activation="relu"),
    layers.MaxPooling2D(),
    layers.Flatten(),
    layers.Dense(64, activation="relu"),
    layers.Dropout(0.3),
    layers.Dense(3, activation="softmax")
])

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

model.summary()

# Train
history = model.fit(
    X_train, y_train,
    epochs=10,
    batch_size=32,
    validation_split=0.2,
    verbose=1
)

# Evaluate
loss, accuracy = model.evaluate(X_test, y_test, verbose=0)

print("\nTest Loss:", round(loss, 4))
print("Test Accuracy:", round(accuracy * 100, 2), "%")

# Plot training curves
plt.figure(figsize=(12, 4))

plt.subplot(1, 2, 1)
plt.plot(history.history["accuracy"], label="Training")
plt.plot(history.history["val_accuracy"], label="Validation")
plt.title("Accuracy")
plt.legend()

plt.subplot(1, 2, 2)
plt.plot(history.history["loss"], label="Training")
plt.plot(history.history["val_loss"], label="Validation")
plt.title("Loss")
plt.legend()

plt.tight_layout()
plt.show()

# Save model
model.save("rps_model.keras")
print("\nModel saved as rps_model.keras")

# Sample prediction
sample = X_test[0]
prediction = model.predict(np.expand_dims(sample, axis=0), verbose=0)

labels = ["Rock", "Paper", "Scissors"]
predicted_class = np.argmax(prediction)

plt.imshow(sample.squeeze(), cmap="gray")
plt.title("Predicted: " + labels[predicted_class])
plt.axis("off")
plt.show()

print("Predicted class:", labels[predicted_class])
print("Confidence:", round(float(prediction[0][predicted_class]) * 100, 2), "%")

print("\nProject completed successfully!")