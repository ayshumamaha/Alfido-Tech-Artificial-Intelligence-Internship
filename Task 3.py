# Movie Review Sentiment Analyzer

print("===== Movie Review Sentiment Analyzer =====")

positive_words = [
    "good", "great", "excellent", "amazing", "awesome",
    "wonderful", "best", "love", "enjoy", "beautiful",
    "interesting", "fantastic", "superb", "brilliant", "happy"
]

negative_words = [
    "bad", "worst", "terrible", "awful", "boring",
    "poor", "hate", "disappointing", "ugly", "waste",
    "horrible", "sad", "dull", "weak", "annoying"
]

review = input("\nEnter your movie review: ").lower()

positive_count = 0
negative_count = 0

words = review.split()

for word in words:
    word = word.strip(".,!?;:\"'()[]{}")

    if word in positive_words:
        positive_count += 1
    elif word in negative_words:
        negative_count += 1

print("\n===== Sentiment Analysis Result =====")
print("Positive words:", positive_count)
print("Negative words:", negative_count)

if positive_count > negative_count:
    print("Sentiment: Positive 😊")
elif negative_count > positive_count:
    print("Sentiment: Negative 😞")
else:
    print("Sentiment: Neutral 😐")