# Loan Approval Fairness & Model Interpretation

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score
)
from sklearn.inspection import permutation_importance

print("=" * 60)
print("LOAN APPROVAL FAIRNESS ANALYSIS")
print("=" * 60)

np.random.seed(42)

# Generate sample dataset
n = 1000

df = pd.DataFrame({
    "Income": np.random.randint(15000, 150000, n),
    "CreditScore": np.random.randint(300, 850, n),
    "LoanAmount": np.random.randint(5000, 300000, n),
    "EmploymentYears": np.random.randint(0, 30, n),
    "Group": np.random.choice(["Group A", "Group B"], n)
})

# Create sample loan approval target
approval_score = (
    (df["Income"] / 150000) * 0.35
    + (df["CreditScore"] / 850) * 0.40
    + (df["EmploymentYears"] / 30) * 0.15
    - (df["LoanAmount"] / 300000) * 0.10
)

# Simulated dataset group-related imbalance
approval_score += np.where(df["Group"] == "Group A", 0.05, -0.05)

df["Approved"] = (
    approval_score + np.random.normal(0, 0.08, n) > 0.48
).astype(int)

print("\nDataset Preview:")
print(df.head())

# Sensitive group excluded from training features
X = df.drop(["Approved", "Group"], axis=1)
y = df["Approved"]
groups = df["Group"]

# Split data
X_train, X_test, y_train, y_test, g_train, g_test = train_test_split(
    X, y, groups,
    test_size=0.2,
    random_state=42,
    stratify=y
)

# Train model
model = RandomForestClassifier(
    n_estimators=150,
    max_depth=6,
    random_state=42
)

model.fit(X_train, y_train)

# Predictions
predictions = model.predict(X_test)

# Overall evaluation
print("\nMODEL PERFORMANCE")
print("Accuracy:", round(accuracy_score(y_test, predictions), 4))
print("Precision:", round(precision_score(y_test, predictions), 4))
print("Recall:", round(recall_score(y_test, predictions), 4))
print("F1 Score:", round(f1_score(y_test, predictions), 4))

# Feature importance
importance = pd.Series(
    model.feature_importances_,
    index=X.columns
).sort_values(ascending=False)

print("\nFEATURE IMPORTANCE:")
print(importance)

importance.plot(kind="bar", figsize=(8, 5))
plt.title("Feature Importance")
plt.ylabel("Importance")
plt.tight_layout()
plt.show()

# SHAP explanations
try:
    import shap

    print("\nGenerating SHAP explanations...")

    explainer = shap.TreeExplainer(model)
    shap_values = explainer.shap_values(X_test)

    # Handle binary-class output shape
    if isinstance(shap_values, list):
        values = shap_values[1]
    else:
        values = shap_values

    if len(values.shape) == 3:
        values = values[:, :, 1]

    shap.summary_plot(values, X_test, show=False)
    plt.title("SHAP Summary Plot")
    plt.tight_layout()
    plt.show()

    # Explain one prediction
    shap.force_plot(
        explainer.expected_value[1]
        if isinstance(explainer.expected_value, np.ndarray)
        else explainer.expected_value,
        values[0],
        X_test.iloc[0],
        matplotlib=True,
        show=False
    )

    plt.title("Local SHAP Explanation")
    plt.tight_layout()
    plt.show()

except ImportError:
    print("\nSHAP is not installed.")
    print("Install using: pip install shap")

# Group fairness analysis
test_data = X_test.copy()
test_data["Actual"] = y_test.values
test_data["Predicted"] = predictions
test_data["Group"] = g_test.values

print("\nGROUP FAIRNESS ANALYSIS")

group_results = []

for group in test_data["Group"].unique():
    subset = test_data[test_data["Group"] == group]

    accuracy = accuracy_score(subset["Actual"], subset["Predicted"])
    precision = precision_score(
        subset["Actual"], subset["Predicted"], zero_division=0
    )
    recall = recall_score(
        subset["Actual"], subset["Predicted"], zero_division=0
    )
    selection_rate = subset["Predicted"].mean()

    group_results.append({
        "Group": group,
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "Selection Rate": selection_rate
    })

group_df = pd.DataFrame(group_results).set_index("Group")

print(group_df.round(4))

# Selection rate comparison
group_df["Selection Rate"].plot(
    kind="bar", figsize=(7, 5)
)

plt.title("Loan Approval Selection Rate by Group")
plt.ylabel("Selection Rate")
plt.ylim(0, 1)
plt.tight_layout()
plt.show()

if len(group_df) >= 2:
    difference = abs(
        group_df["Selection Rate"].iloc[0]
        - group_df["Selection Rate"].iloc[1]
    )

    print("\nSelection Rate Difference:", round(difference, 4))

    if difference > 0.10:
        print("Notice: A group outcome difference was observed.")
    else:
        print("No large selection-rate difference in this sample.")

